'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {calculateRecipeConsumption,calculateBalance}=require('../src/services/inventory-math');
test('calculates recipe consumption for fractional sales quantities',()=>{assert.equal(calculateRecipeConsumption(0.250,2,1),0.5);});
test('rounds ingredient consumption upward to three decimal places',()=>{assert.equal(calculateRecipeConsumption(0.1001,1,1),0.101);});
test('rejects zero and negative recipe quantities',()=>{assert.throws(()=>calculateRecipeConsumption(0,1,1),/positive finite numbers/);assert.throws(()=>calculateRecipeConsumption(1,-1,1),/positive finite numbers/);});
test('adds stock movements accurately to three decimal places',()=>{assert.equal(calculateBalance(2.125,0.375),2.5);});
test('prevents stock from becoming negative',()=>{assert.throws(()=>calculateBalance(1,-1.001),{code:'INSUFFICIENT_STOCK'});});
test('rejects invalid stock balances',()=>{assert.throws(()=>calculateBalance(-1,1),/finite and current stock cannot be negative/);});
